<?php
namespace php_active_record;
/* This analyzes the MoF extension
php update_resources/connectors/analyze_MoF.php _ '{"resource_id": "fishbase_final"}' //fishbase_final.tar.gz
*/
include_once(dirname(__FILE__) . "/../../config/environment.php");
// /* during development
ini_set('error_reporting', E_ALL);
ini_set('display_errors', true);
$GLOBALS['ENV_DEBUG'] = true; //set to true during development
// */
ini_set('memory_limit','10096M');
$timestart = time_elapsed();

// print_r($argv);
$params['jenkins_or_cron'] = @$argv[1]; //not needed here
$param                     = json_decode(@$argv[2], true); // print_r($param); exit;
$resource_id = $param['resource_id'];

$tmp_id = $param['resource_id']; //e.g. "fishbase_final"
$dwca_file = DOC_ROOT . "/applications/content_server/resources/".$tmp_id.".tar.gz";
$resource_id .= "_analyzed"; //the DwCA with MoF extension analyzed

// /* Lock: only one run per resource at a time. Two runs of the same resource share the same working folder
// ([resource_id]_working) and corrupt each other's output (e.g. WoRMS_finale on 2026-11-18: empty agent.tab, crash).
// flock() is released automatically when this process ends, even on a crash, so a stale .lock file is harmless.
$lock_file = CONTENT_RESOURCE_LOCAL_PATH . $resource_id . ".lock";
$lock = fopen($lock_file, 'c+');
if(!$lock || !flock($lock, LOCK_EX | LOCK_NB)) {
    $holder = $lock ? trim(stream_get_contents($lock)) : '';
    echo "\nERROR: [$resource_id] is already being generated by another run".($holder ? " ($holder)" : "").".\n";
    echo "Lock file: $lock_file\nWait for that run to finish, then try again. Will terminate.\n";
    exit(1); // non-zero, so a Jenkins job is marked as failed
}
ftruncate($lock, 0); fwrite($lock, "started ".date('Y-m-d H:i:s T')." by pid ".getmypid()." on ".gethostname()); fflush($lock);
// */

process_resource_url($dwca_file, $resource_id, $timestart);

flock($lock, LOCK_UN); fclose($lock); @unlink($lock_file);

function process_resource_url($dwca_file, $resource_id, $timestart)
{
    require_library('connectors/DwCA_Utility');
    $params['resource'] = "analyze_MoF";
    $func = new DwCA_Utility($resource_id, $dwca_file, $params);
    $preferred_rowtypes = array();
    $excluded_rowtypes = array();

    $excluded_rowtypes = array('http://eol.org/schema/association', 'http://rs.tdwg.org/dwc/terms/measurementorfact', 'http://rs.tdwg.org/dwc/terms/occurrence');
    // these 3 will be processed in AnalyzeMoF_API.php. The rest will be saved in DwCA_Utility.php.

    // media, agent, and vernacular name files can be discarded.
    $excluded_rowtypes[] = 'http://eol.org/schema/media/document';
    $excluded_rowtypes[] = 'http://eol.org/schema/agent/agent';
    $excluded_rowtypes[] = 'http://rs.gbif.org/terms/1.0/vernacularname';

    /* This will be processed in AnalyzeMoF_API.php which will be called from DwCA_Utility.php */
    $func->convert_archive($preferred_rowtypes, $excluded_rowtypes);
    Functions::finalize_dwca_resource($resource_id, false, true, $timestart);

    // recursive_rmdir(CONTENT_RESOURCE_LOCAL_PATH . '/'.$resource_id.'_working');
    // unlink(CONTENT_RESOURCE_LOCAL_PATH . '/'.$resource_id.'_working.tar.gz');
}
?>
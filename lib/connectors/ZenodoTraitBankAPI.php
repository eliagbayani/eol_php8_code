class ZenodoTraitBankAPI
{
    function __construct($folder = null, $query = null)
    {
        $this->download_options = array(
            'resource_id'        => 'zenodo',  //resource_id here is just a folder name in cache
            'expire_seconds'     => 60*60*24*1, //maybe 1 day to expire
            'download_wait_time' => 1000000, 'timeout' => 60*3, 'download_attempts' => 1, 'delay_in_minutes' => 0.5);
        // $this->download_options['expire_seconds'] = 0;
        $this->download_options['expire_seconds'] = 60*60*24*30; //for eol content partners
        $this->api['domain'] = 'https://zenodo.org';
    }
    function get_zenodo_info_using_conceptID($conceptId)
    {
        $ch = curl_init("https://zenodo.org/api/records/{$conceptId}/versions/latest");
        curl_setopt_array($ch, [
            CURLOPT_RETURNTRANSFER => true,
            CURLOPT_FOLLOWLOCATION => true,
            CURLOPT_HTTPHEADER     => ["Accept: application/json"],
            // CURLOPT_HTTPHEADER  => ["Accept: application/json", "Authorization: Bearer YOUR_TOKEN"], // restricted records
        ]);
        $body   = curl_exec($ch);
        $status = curl_getinfo($ch, CURLINFO_HTTP_CODE);
        curl_close($ch);

        if ($body === false || $status !== 200) {
            exit("Request failed (HTTP $status)\n");
        }

        $rec = json_decode($body, true);

        // A. Zip of all files in the record (generated by Zenodo)
        $archiveUrl = $rec["links"]["archive"] ?? null;

        // B. Any uploaded .zip files (e.g. GitHub release archives)
        $zipFiles = [];
        foreach ($rec["files"] ?? [] as $f) {
            if (str_ends_with($f["key"], ".zip")) {   // PHP 8+; use substr($f["key"], -4) === ".zip" on PHP 7
                $zipFiles[] = $f["links"]["self"];
            }
        }

        echo "Latest record ID: {$rec['id']}\n";
        echo "Version: " . ($rec["metadata"]["version"] ?? "n/a") . "\n";
        echo "Archive URL: $archiveUrl\n";
        echo "Uploaded zip(s):\n" . implode("\n", $zipFiles) . "\n";
    }
}
